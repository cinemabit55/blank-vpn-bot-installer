def _site_tagline(config: NodeConfig) -> str:
    choices = (
        'Clear digital work for practical teams.',
        'Small websites, useful systems, steady support.',
        'Simple web presence with careful maintenance.',
        'Focused digital pages for everyday operations.',
    )
    return choices[_stable_index(config.display.internal_name, len(choices))]


def _site_accent(config: NodeConfig) -> str:
    accents = ('#236b5f', '#315f72', '#725a31', '#663f5f', '#4d6743')
    return accents[_stable_index(config.domain, len(accents))]


def _favicon_svg(config: NodeConfig) -> str:
    accent = _site_accent(config)
    initial = escape(config.site.title.strip()[:1].upper() or 'D')
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">
  <rect width="64" height="64" rx="12" fill="{accent}"/>
  <text x="32" y="41" text-anchor="middle" font-family="Arial, sans-serif" font-size="30" font-weight="700" fill="#fff">{initial}</text>
</svg>
"""


def _robots_txt() -> str:
    return 'User-agent: *\nAllow: /\n'


def _stable_index(value: str, modulo: int) -> int:
    return sum(value.encode('utf-8')) % modulo


def _reality_snippet(config: NodeConfig) -> dict:
    snippet = {
        'strategy': config.reality.strategy.value,
        'public_port': config.reality.public_port,
        'flow': config.reality.flow,
        'serverNames': config.effective_reality_server_names(),
        'credentials_ref': config.reality.credentials_ref,
        'network': config.reality.transport.value,
        'security': 'reality',
        'realitySettings': '<filled-by-layer-2-from-secret-material>',
    }
    if config.reality.transport == RealityTransport.XHTTP:
        snippet['xhttpSettings'] = config.reality.xhttp.model_dump(mode='json') if config.reality.xhttp else None
    if config.reality.strategy == RealityStrategy.LOCAL_DECOY_SITE:
        snippet['dest'] = f'{config.reality.local_decoy_addr}:{config.reality.local_decoy_port}'
    else:
        snippet['dest'] = config.reality.target
    return snippet


def _warp_snippet(config: NodeConfig) -> dict | None:
    if config.warp.mode != WarpMode.XRAY_NATIVE:
        return None
    return {
        'tag': config.warp.outbound_tag,
        'protocol': 'wireguard',
        'settings': {
            'reserved': config.warp.reserved or '<computed-from-warp-registration-client-id>',
            'secret_ref': config.warp.registration_ref,
            'kernelMode': False,
            'mtu': 1280,
            'domainStrategy': 'ForceIPv4',
        },
    }


def _transit_snippet(config: NodeConfig) -> dict | None:
    if config.transit.mode != TransitMode.VLESS_REALITY:
        return None
    if config.role == NodeRole.FOREIGN_EXIT:
        return {
            'direction': 'inbound',
            'tag': config.transit.inbound_tag,
            'listen_port': config.transit.listen_port,
            'flow': config.transit.flow,
            'allow_from': config.transit.allow_from,
            'service_user': config.transit.service_user,
            'service_user_credential_ref': config.transit.service_user_credential_ref,
            'reality_credentials_ref': config.transit.reality_credentials_ref,
        }
    return {
        'direction': 'outbound',
        'tag': config.transit.outbound_tag,
        'foreign_exit': f'{config.transit.foreign_exit_domain}:{config.transit.foreign_exit_port}',
        'serverNames': config.transit.server_names,
        'service_user_credential_ref': config.transit.service_user_credential_ref,
        'reality_credentials_ref': config.transit.reality_credentials_ref,
        'backup_outbounds': [backup.model_dump(mode='json') for backup in config.transit.backup_outbounds],
    }


def _routing_snippet(config: NodeConfig) -> dict | None:
    if config.role != NodeRole.RU_EDGE or config.routing is None:
        return None
    return {
        'domainStrategy': 'IPIfNonMatch',
        'sniffing': {
            'enabled': True,
            'destOverride': ['http', 'tls', 'quic'],
            'routeOnly': True,
        },
        'rules_order': [
            'BLOCK private/bittorrent',
            'DNS resolver endpoint rules',
            'RU geo/site/allow-list direct',
            'PUBLIC_RU_INBOUND fallback to TRANSIT_TO_FOREIGN',
        ],
        'ru_dns': config.routing.ru_dns,
        'foreign_dns_via_transit': config.routing.foreign_dns_via_transit,
    }
