@dataclass(frozen=True)
class RenderedArtifact:
    relative_path: str
    content: str
    mode: str = '0644'


@dataclass(frozen=True)
class RenderedBundle:
    artifacts: tuple[RenderedArtifact, ...]

    def names(self) -> list[str]:
        return [artifact.relative_path for artifact in self.artifacts]


def render_bundle(config: NodeConfig, *, secret_store: LocalSecretStore | None = None) -> RenderedBundle:
    artifacts = [
        RenderedArtifact('opt/remnanode/.env', render_remnanode_env(config, secret_store), mode='0600'),
        RenderedArtifact('opt/remnanode/docker-compose.yml', render_remnanode_compose(config)),
        RenderedArtifact('etc/caddy/Caddyfile', render_caddyfile(config)),
        RenderedArtifact('opt/templar-node/ufw-plan.txt', render_ufw_plan(config)),
        RenderedArtifact('opt/templar-node/network-tuning.sh', render_network_tuning_script(config), mode='0755'),
        RenderedArtifact('etc/systemd/system/templar-node-network-tuning.service', render_network_tuning_service()),
        RenderedArtifact('opt/templar-node/xray-snippets.json', render_xray_snippets(config)),
    ]
    artifacts.extend(render_site_artifacts(config))
    return RenderedBundle(artifacts=tuple(artifacts))


def write_bundle(bundle: RenderedBundle, output_dir: str | Path) -> list[Path]:
    root = Path(output_dir)
    written: list[Path] = []
    for artifact in bundle.artifacts:
        path = root / artifact.relative_path
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(artifact.content, encoding='utf-8')
        path.chmod(int(artifact.mode, 8))
        written.append(path)
    return written


def render_remnanode_env(config: NodeConfig, secret_store: LocalSecretStore | None = None) -> str:
    secret_value = '<resolved-by-layer-1-from-secret-store>'
    if secret_store is not None:
        secret_value = secret_store.read_text(config.remnanode.secret_key_ref)

    lines = [
        '# Generated by templar-node. Do not commit real values.',
        f'NODE_PORT={config.remnanode.node_port}',
        f'XTLS_API_PORT={config.xray.xtls_api_port}',
        f'SECRET_KEY={secret_value}',
    ]
    return '\n'.join(lines) + '\n'


def render_remnanode_compose(config: NodeConfig) -> str:
    service = {
        'image': 'remnawave/node:latest',
        'container_name': config.display.internal_name.lower().replace('_', '-'),
        'restart': 'always',
        'network_mode': 'host',
        'env_file': '.env',
        'volumes': [
            './data:/var/lib/remnanode',
            './logs:/var/log/remnanode',
        ],
        'logging': {
            'driver': 'json-file',
            'options': {
                'max-size': '50m',
                'max-file': '5',
            },
        },
    }
    if config.warp.mode == WarpMode.XRAY_NATIVE:
        service['privileged'] = True
        service['cap_add'] = ['NET_ADMIN']
        service['devices'] = ['/dev/net/tun:/dev/net/tun']

    compose = {
        'services': {
            'remnanode': service,
        },
    }
    return yaml.safe_dump(compose, sort_keys=False)


